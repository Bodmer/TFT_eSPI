void setup() {
  // DAC setup
  dac_output_enable(DAC_CHANNEL_1);    // pin 25
  dac_output_voltage(DAC_CHANNEL_1, 0);

  Serial.begin(115200);
  analogReadResolution(12);
  analogSetPinAttenuation(peakDetectorPin, ADC_11db);
  analogSetPinAttenuation(invertedPeakDetectorPin, ADC_11db);
  analogSetPinAttenuation(gainPotPin, ADC_11db);
  analogSetPinAttenuation(frequencyScalePotPin, ADC_11db);
  pinMode(frequencyInputPin, INPUT);

  display.init();
  drawStaticUi();
  updateControlMeasurements();
  updatePeakDetectors(micros());
  configureFrequencyCounter();
  configureAdcCapture();
  if (xTaskCreatePinnedToCore(adcCaptureTask, "adc_capture", 4096, nullptr, 3,
                              &adcCaptureTaskHandle, 0) != pdPASS) {
    ESP_ERROR_CHECK(ESP_FAIL);
  }
  lastControlUpdateMs = millis();
  drawDashboard();
  displayRateWindowStartMs = millis();
  drawDisplayChangeRate();
  lastDisplayFrameUs = micros();
  Serial.println(
      "Measurement inputs ready: ADC GPIO34/35/32/33; frequency counter GPIO27.");
  Serial.printf(
      "ADC capture ready: 8-bit D11..D4 on GPIO36,26,22,21,17,16,14,13; "
      "clock GPIO15, loopback GPIO39; %u samples per capture.\n",
      static_cast<unsigned>(adcCaptureSampleCount));
}

void loop() {
  const uint32_t nowUs = micros();
  updatePeakDetectors(nowUs);
  updateFrequencyMeasurement(nowUs);

  const uint32_t nowMs = millis();

  if (nowMs - lastControlUpdateMs >= potentiometerUpdatePeriodMs) {
    const int previousSamplingRate = Sampling_rate;
    updateControlMeasurements();
    lastControlUpdateMs = nowMs;
    if (Sampling_rate != previousSamplingRate) {
      ESP_ERROR_CHECK(pcnt_counter_pause(PCNT_UNIT_0));
      ESP_ERROR_CHECK(pcnt_counter_clear(PCNT_UNIT_0));
      ESP_ERROR_CHECK(pcnt_counter_resume(PCNT_UNIT_0));
      frequencyWindowStartUs = micros();
      clearFrequencyEstimate();
    }
  }

  const uint32_t rateWindowElapsedMs = nowMs - displayRateWindowStartMs;
  if (rateWindowElapsedMs >= 1000) {
    displayChangeRateHz =
        displayChangeFrames * (1000.0f / rateWindowElapsedMs);
    displayChangeFrames = 0;
    displayRateWindowStartMs = nowMs;
    displayRateReady = true;
  }

  if (nowUs - lastDisplayFrameUs >= minimumDisplayFrameIntervalUs) {
    lastDisplayFrameUs = nowUs;
    bool frameChanged = drawDashboard();
    if (adcCaptureReady) {
      frameChanged |= drawSignalPlot();
      __sync_synchronize();
      adcCaptureReady = false;
      __sync_synchronize();
    }
    drawDisplayChangeRate();
    if (frameChanged && displayChangeFrames < UINT16_MAX) {
      ++displayChangeFrames;
    }
  }
  taskYIELD();
}
